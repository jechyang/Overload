using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Overload.SerializationGenerator;

[Generator]
public sealed class FieldSchemaGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor InvalidIdentity = new("OVSG001", "Invalid serialized field identity",
        "Serialized field '{0}': {1}", "Overload.Serialization", DiagnosticSeverity.Error, true);
    private static readonly DiagnosticDescriptor ReflectionFallback = new("OVSG002", "Field schema requires compatibility access",
        "'{0}' contains an inaccessible or generic field type; its fields use the compatibility schema", "Overload.Serialization", DiagnosticSeverity.Info, true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var types = context.SyntaxProvider.CreateSyntaxProvider(
            static (node, _) => node is TypeDeclarationSyntax,
            static (syntax, _) => syntax.SemanticModel.GetDeclaredSymbol((TypeDeclarationSyntax)syntax.Node) as INamedTypeSymbol)
            .Where(static symbol => symbol != null).Collect();
        context.RegisterSourceOutput(types, static (output, symbols) => Emit(output, symbols));
    }

    private static bool Has(ISymbol symbol, string attribute) => symbol.GetAttributes().Any(a => a.AttributeClass?.ToDisplayString() == attribute);
    private static string? Text(ISymbol symbol, string attribute) => symbol.GetAttributes()
        .FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == attribute)?.ConstructorArguments.FirstOrDefault().Value as string;
    private static bool Eligible(INamedTypeSymbol type)
    {
        if (Has(type, "System.SerializableAttribute")) return true;
        for (var parent = type.BaseType; parent != null; parent = parent.BaseType)
            if (parent.ToDisplayString() == "Overload.Behaviour") return true;
        return false;
    }
    private static bool Accessible(ITypeSymbol type) => type switch {
        IArrayTypeSymbol array => Accessible(array.ElementType),
        INamedTypeSymbol named => !named.IsFileLocal && !named.IsRefLikeType && !named.IsUnboundGenericType &&
            named.TypeArguments.All(Accessible) &&
            named.DeclaredAccessibility is not (Accessibility.Private or Accessibility.Protected or Accessibility.ProtectedAndInternal) &&
            (named.ContainingType == null || Accessible(named.ContainingType)),
        _ => type.TypeKind != TypeKind.TypeParameter && type.TypeKind != TypeKind.Pointer && type.TypeKind != TypeKind.FunctionPointer
    };
    private static IFieldSymbol[] Fields(INamedTypeSymbol type) => type.GetMembers().OfType<IFieldSymbol>()
        .Where(f => !f.IsStatic && !f.IsReadOnly && !f.IsConst && (!f.IsImplicitlyDeclared || Has(f, "Overload.SerializeFieldAttribute")) && !Has(f, "System.NonSerializedAttribute") &&
            (f.DeclaredAccessibility == Accessibility.Public || Has(f, "Overload.SerializeFieldAttribute"))).ToArray();
    private static string TypeName(ITypeSymbol symbol) => symbol is IDynamicTypeSymbol ? "global::System.Object" : symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
    private static string Quote(string value) => SymbolDisplay.FormatLiteral(value, true);
    private static bool Identity(string value) => !string.IsNullOrWhiteSpace(value) && !value.Any(char.IsControl);

    private static void Emit(SourceProductionContext output, ImmutableArray<INamedTypeSymbol?> symbols)
    {
        var types = symbols.OfType<INamedTypeSymbol>().Distinct<INamedTypeSymbol>(SymbolEqualityComparer.Default)
            .Where(Eligible).OrderBy(t => t.ToDisplayString(), StringComparer.Ordinal).ToArray();
        if (types.Length == 0) return;
        var source = new StringBuilder("// <auto-generated/>\n#nullable enable\nnamespace Overload.Generated;\npublic sealed class __FieldSchemaProvider : global::Overload.IFieldSchemaProvider\n{\n");
        var entries = new StringBuilder();
        int index = 0;
        foreach (var type in types) {
            var fields = Fields(type);
            // Check identities across inherited fields, including fields in referenced assemblies.
            var keys = new HashSet<string>(StringComparer.Ordinal);
            for (var owner = type; owner != null && owner.ToDisplayString() != "Overload.Behaviour"; owner = owner.BaseType)
            foreach (var field in Fields(owner)) {
                string id = Text(field, "Overload.FieldIdAttribute") ?? field.Name;
                var aliases = Aliases(field, id);
                foreach (string key in new[] { id }.Concat(aliases))
                    if (!Identity(key) || !keys.Add(key)) output.ReportDiagnostic(Diagnostic.Create(InvalidIdentity,
                        field.Locations.FirstOrDefault(), field.ToDisplayString(), !Identity(key) ? "empty or control-character identity" : "duplicate ID/alias " + key));
            }
            if (type.IsGenericType || !Accessible(type) || fields.Any(f => !Accessible(f.Type))) {
                output.ReportDiagnostic(Diagnostic.Create(ReflectionFallback, type.Locations.FirstOrDefault(), type.ToDisplayString()));
                continue;
            }
            string ownerName = TypeName(type), arrayName = "Fields" + index;
            entries.Append("        if (type == typeof(").Append(ownerName).Append(")) return ").Append(arrayName).Append(";\n");
            source.Append("    private static readonly global::Overload.GeneratedFieldDescriptor[] ").Append(arrayName).Append(" = new global::Overload.GeneratedFieldDescriptor[] {\n");
            int first = index;
            foreach (var field in fields) {
                string id = Text(field, "Overload.FieldIdAttribute") ?? field.Name;
                string fieldType = TypeName(field.Type), access = "Access" + index++;
                string receiver = type.IsValueType ? "ref global::System.Runtime.CompilerServices.Unsafe.Unbox<" + ownerName + ">(instance)" : "(" + ownerName + ")instance";
                source.Append("        new(").Append(Quote(id)).Append(", ").Append(Quote(field.Name)).Append(", ")
                    .Append(Quote(Text(field, "Overload.InspectorNameAttribute") ?? field.Name)).Append(", new string[] { ")
                    .Append(string.Join(", ", Aliases(field, id).Select(Quote))).Append(" }, typeof(").Append(fieldType).Append("), ")
                    .Append(field.DeclaredAccessibility == Accessibility.Public ? "true" : "false").Append(",\n            static instance => ")
                    .Append(access).Append('(').Append(receiver).Append("), static (instance, value) => ").Append(access).Append('(').Append(receiver)
                    .Append(") = (").Append(fieldType).Append(")value!),\n");
            }
            source.Append("    };\n");
            index = first;
            foreach (var field in fields) {
                source.Append("    [global::System.Runtime.CompilerServices.UnsafeAccessor(global::System.Runtime.CompilerServices.UnsafeAccessorKind.Field, Name = ")
                    .Append(Quote(field.Name)).Append(")]\n    private static extern ref ").Append(TypeName(field.Type)).Append(" Access").Append(index++)
                    .Append('(').Append(type.IsValueType ? "ref " : "").Append(ownerName).Append(" instance);\n");
            }
            // Empty schemas must still be distinct and authoritative.
            if (fields.Length == 0) ++index;
        }
        source.Append("    public global::Overload.GeneratedFieldDescriptor[]? GetDeclaredFields(global::System.Type type)\n    {\n")
            .Append(entries).Append("        return null;\n    }\n}\n");
        output.AddSource("Overload.FieldSchema.g.cs", source.ToString());
    }
    private static string[] Aliases(IFieldSymbol field, string id)
    {
        var aliases = field.GetAttributes().Where(a => a.AttributeClass?.ToDisplayString() == "Overload.FormerlySerializedAsAttribute")
            .Select(a => a.ConstructorArguments.FirstOrDefault().Value as string ?? "").ToList();
        if (id != field.Name && !aliases.Contains(field.Name, StringComparer.Ordinal)) aliases.Add(field.Name);
        return aliases.ToArray();
    }
}
