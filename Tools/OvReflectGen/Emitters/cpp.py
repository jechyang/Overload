"""Deterministic C++20 emitter consuming the validated, language-neutral R1 Schema."""
import hashlib
import json
from pathlib import Path
import re

from Emitters import script

OUTPUTS = ("Reflection.generated.h", "Reflection.generated.cpp", *script.OUTPUTS, "manifest.json")


def quote(value):
    # Emit UTF-8 as fixed-width octal bytes: independent of execution charset,
    # and no C++ hexadecimal escape can consume following identifier characters.
    return '"' + ''.join(chr(b) if 32 <= b < 127 and b not in (34, 92)
                         else '\\%03o' % b for b in value.encode("utf-8")) + '"'


def source(item):
    s = item["source"]
    return "Source{" + f'{quote(s["path"])}, {s["line"]}, {s["column"]}' + "}"


def value_type(t):
    return "ValueType{" + ", ".join([quote(t[k]) for k in ("display", "canonical", "value_type", "category")] +
        [str(t["bits"]), str(t["signed"]).lower(), f'Key<{t["value_type"]}>()']) + "}"


def emit(schema, directory, *, types=None, dependencies=(), known_types=None, value_codecs=False, component_adapters=False):
    """Input is trusted output from LibTooling, never unvalidated user C++ snippets."""
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    for name in OUTPUTS:
        (directory / name).unlink(missing_ok=True)
    if schema["schema_version"] != 1:
        raise ValueError("Unsupported Schema version for C++ generation")
    module = schema["module"]
    if not re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*", module):
        raise ValueError("Module must be a C++ identifier")
    types = sorted(schema["types"] if types is None else types, key=lambda t: t["id"])
    known = set(known_types if known_types is not None else (t["cpp_name"] for t in types))
    header = ["// Generated by OvReflectGen. Do not edit.", "#pragma once",
              "#include <OvReflection/Reflection.h>"]
    header += [f'#include "{p}"' for p in sorted(dependencies)]
    header += [f'#include "{p}"' for p in sorted({t["source"]["path"] for t in types})]
    header += ["namespace OvReflection", "{"]
    for t in types:
        cpp = "::" + t["cpp_name"]
        header += [f"    template<> struct Traits<{cpp}> {{ static const TypeDesc& Get(); }};"]
    header += [f"    Error Register{module}Types(Registry& registry);"]
    impl = ['// Generated by OvReflectGen. Do not edit.', '#include "Reflection.generated.h"',
            "namespace OvReflection", "{"]

    def array(name, kind, values):
        impl.append(f'        static const std::array<{kind}, {len(values)}> {name}{{{{')
        impl.extend("            " + v + "," for v in values)
        impl.append("        }};")
        return name

    def aliases(name, item):
        return array(name, "std::string_view", [quote(a) for a in item["aliases"]])

    def metadata(name, item):
        return array(name, "Metadata", ["Metadata{" + quote(k) + ", " + quote(v) + "}"
                     for k, v in sorted(item["metadata"].items())])

    for t in types:
        cpp = "::" + t["cpp_name"]
        header += [f"    template<> struct Access<{cpp}>", "    {"]
        # Access methods have stable C++ member-derived names, not logical IDs.
        for p in t["properties"]:
            member = p["cpp_name"].split("::")[-1]
            v = p["type"]["value_type"]
            thread = p["metadata"].get("Thread", "Main" if "Component" in t["metadata"] else "Any")
            getter = f'object.{member}' if p["strategy"] == "field" else f'object.{p["getter"].split("::")[-1]}()'
            header += [f"        static Error Read_{member}(const MainThread& main, const {cpp}& object, {v}& output)",
                       "        {", f"            if (auto error = main.Check(Thread::{thread}); error != Error::None) return error;",
                       f"            output = {getter};", "            return Error::None;", "        }"]
            if not p["read_only"]:
                setter = f'object.{member} = input' if p["strategy"] == "field" else f'object.{p["setter"].split("::")[-1]}(input)'
                header += [f"        static Error Write_{member}(const MainThread& main, {cpp}& object, const std::type_identity_t<{v}>& input)",
                           "        {", f"            if (auto error = main.Check(Thread::{thread}); error != Error::None) return error;",
                           f"            {setter};", "            return Error::None;", "        }"]
        header += script.access_methods(t)
        header += ["    };"]
        impl += [f"    const TypeDesc& Traits<{cpp}>::Get()", "    {"]
        ta, tm = aliases("typeAliases", t), metadata("typeMetadata", t)
        properties = []
        for i, p in enumerate(t["properties"]):
            pa, pm = aliases(f"p{i}Aliases", p), metadata(f"p{i}Metadata", p)
            member = p["cpp_name"].split("::")[-1]
            setter = "nullptr" if p["read_only"] else f"&Access<{cpp}>::Write_{member}"
            thread = p["metadata"].get("Thread", "Main" if "Component" in t["metadata"] else "Any")
            fields = [quote(p[k]) for k in ("id", "name", "cpp_name", "strategy", "access")]
            fields += [value_type(p["type"]), str(p["read_only"]).lower(), f"Thread::{thread}", pa, pm, source(p)]
            properties += [f'PropertyDesc::Make<{cpp}, {p["type"]["value_type"]}, &Access<{cpp}>::Read_{member}, {setter}>'
                           + "(PropertyInfo{" + ", ".join(fields) + "})"]
        array("properties", "PropertyDesc", properties)
        methods = []
        for i, m in enumerate(t["methods"]):
            ma, mm = aliases(f"m{i}Aliases", m), metadata(f"m{i}Metadata", m)
            params = array(f"m{i}Parameters", "ParameterDesc",
                           ["ParameterDesc{" + quote(p["name"]) + ", " + value_type(p["type"]) + "}" for p in m["parameters"]])
            fields = [quote(m[k]) for k in ("id", "name", "cpp_name", "signature", "access", "ref_qualifier")]
            fields += [str(m["const"]).lower(), str(m["noexcept"]).lower(), value_type(m["return_type"]), params, ma, mm, source(m)]
            methods.append("MethodDesc{" + ", ".join(fields) + "}")
        array("methods", "MethodDesc", methods)
        bases = []
        for b in t.get("cast_bases", t["bases"]):
            base = "::" + b["cpp_name"]
            reflected = f"+[]() -> const TypeDesc* {{ return &TypeOf<{base}>(); }}" if b["cpp_name"] in known else "nullptr"
            bases.append(f'BaseDesc::Make<{cpp}, {base}>({quote(b["cpp_name"])}, {reflected})')
        array("bases", "BaseDesc", bases)
        array("enumerators", "EnumValue", ["EnumValue{" + quote(e["name"]) + ", " + quote(e["value"]) + ", " + source(e) + "}"
                                         for e in t.get("enumerators", [])])
        kind = {"class": "Class", "struct": "Struct", "enum": "Enum", "enum class": "EnumClass"}[t["kind"]]
        underlying = value_type(t["underlying_type"]) if "underlying_type" in t else "ValueType{}"
        impl += ["        static const TypeDesc descriptor(TypeInfo{" +
                 f'{quote(t["id"])}, {quote(t["cpp_name"])}, {quote(module)}, Kind::{kind}, 1, Key<{cpp}>(), '
                 + f'{ta}, {tm}, {source(t)}, bases, properties, methods, {underlying}, enumerators' + "});",
                 "        return descriptor;", "    }"]
    impl += [f"    Error Register{module}Types(Registry& registry)", "    {"]
    array("types", "const TypeDesc*", [f'&TypeOf<::{t["cpp_name"]}>()' for t in types])
    impl += [f"        return registry.RegisterModule({quote(module)}, types);", "    }", "}"]
    header += ["}"]
    if module == "OvCore" or component_adapters:
        components = sorted((t for t in types if "Component" in t["metadata"]),
                            key=lambda t: (float(t["metadata"].get("Order", "0")), t["id"]))
        impl += ['#include <OvCore/ECS/ComponentFactory.h>', "namespace OvCore::ECS", "{",
                 f"    std::span<const ComponentDesc> Get{module}Components()", "    {"]
        for t in components:
            cpp = "::" + t["cpp_name"]
            # Compatibility traits are checked against the authoritative annotation;
            # they are never used to discover/register types or populate the menu.
            if not t["aliases"]:
                raise ValueError("Native component requires its legacy ComponentTraits alias: " + t["id"])
            checks = " || ".join(f"Components::ComponentTraits<{cpp}>::Name == {quote(a)}" for a in t["aliases"])
            impl.append(f'        static_assert({checks}, "ComponentTraits must match an annotated legacy alias");')
        values = [f'MakeComponentDesc<::{t["cpp_name"]}, {str("Lookup" in t["metadata"]).lower()}>(OvReflection::TypeOf<::{t["cpp_name"]}>())' for t in components]
        array("components", "ComponentDesc", values)
        impl += ["        return components;", "    }", "}"]
    impl += ['#include "Script.generated.inc"']
    if module == "OvCore" or value_codecs:
        adapted = {}
        def adapt(value):
            if value["category"] in ("resource-reference", "resource-array", "record-adapter", "value-array", "value-list"):
                adapted[value["value_type"]] = value
            if "element_type" in value:
                adapt(value["element_type"])
        for t in types:
            for p in t["properties"]:
                adapt(p["type"])
        impl += ['#include <OvCore/Helpers/ReflectionResourceCodecs.h>',
                 '#include <OvCore/Helpers/ReflectionRecordCodecs.h>',
                 '#include <OvCore/Helpers/ReflectionCollectionCodecs.h>',
                 'namespace OvCore::Helpers::ReflectionProperties', '{',
                 f'    std::span<const ValueCodec> Get{module}ValueCodecs()', '    {']
        def codec(v):
            t = adapted[v]
            if t["category"] in ("value-array", "value-list"):
                return f'MakeCollectionCodec<{v}>({value_type(t["element_type"])})'
            return f'Make{"Record" if t["category"] == "record-adapter" else "Resource"}Codec<{v}>()'
        array("codecs", "ValueCodec", [codec(v) for v in sorted(adapted)])
        impl += ['        return codecs;', '    }', '}']
    try:
        script.emit(schema, directory, types)
        for name, lines in (("Reflection.generated.h", header), ("Reflection.generated.cpp", impl)):
            (directory / name).write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
        manifest = {"schema_version": 1, "module": module, "configuration": schema["configuration"],
                    "types": [t["id"] for t in types], "dependencies": sorted(dependencies),
                    "files": [{"path": name, "sha256": hashlib.sha256((directory / name).read_bytes()).hexdigest()}
                              for name in OUTPUTS if name != "manifest.json"]}
        (directory / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8", newline="\n")
    except Exception:
        for name in OUTPUTS:
            (directory / name).unlink(missing_ok=True)
        raise
